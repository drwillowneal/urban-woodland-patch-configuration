# Query the National Forest Inventory ArcGIS REST API for a bounding box
# (BNG coordinates), paging through the results (the service returns at
# most 2,000 records per request). This is used instead of
# sf::st_read(nfi_file, wkt_filter = ...) because GDAL does not apply
# the filter to the local GeoJSON: the file declares its CRS in a
# non-standard property, so BNG filter coordinates match nothing. The
# REST query avoids this by stating inSR and outSR explicitly.
#
# A bounding box covering England needs over 100 requests, so the
# download is resumable: each page is saved to cache_dir as it is
# fetched, and a re-run with the same cache_dir skips pages already on
# disk. Failed requests are retried up to max_retries times with a
# wait that grows with each attempt (3 s, 6 s, 9 s ...). request_delay
# pauses between successful requests to avoid being throttled, and
# download_timeout raises R's default 60 s download limit, which
# otherwise cuts off pages with detailed geometry part-way through.
fetch_nfi_bbox <- function(bbox, page_size = 2000, cache_dir = NULL, max_retries = 5,
                            request_delay = 1, download_timeout = 300) {

  old_timeout <- getOption("timeout")
  options(timeout = download_timeout)
  on.exit(options(timeout = old_timeout), add = TRUE)

  base_url <- paste0(
    "https://services2.arcgis.com/mHXjwgl3OARRqqD4/arcgis/rest/",
    "services/National_Forest_Inventory_GB_2024/FeatureServer/0/query"
  )

  if (!is.null(cache_dir)) {
    dir.create(cache_dir, showWarnings = FALSE, recursive = TRUE)
  }

  pages <- list()
  offset <- 0

  repeat {

    page_file <- if (!is.null(cache_dir)) {
      file.path(cache_dir, sprintf("page_%06d.rds", offset))
    } else {
      NULL
    }

    if (!is.null(page_file) && file.exists(page_file)) {

      page <- readRDS(page_file)
      cat("  Offset", offset, "— loaded from cache\n")

    } else {

      url <- paste0(
        base_url, "?",
        "geometry=", bbox["xmin"], ",", bbox["ymin"], ",",
        bbox["xmax"], ",", bbox["ymax"],
        "&geometryType=esriGeometryEnvelope",
        "&inSR=27700&spatialRel=esriSpatialRelIntersects",
        "&outFields=*&outSR=27700&f=geojson",
        "&resultRecordCount=", page_size,
        "&resultOffset=", offset
      )

      page <- NULL
      attempt <- 1

      while (attempt <= max_retries && is.null(page)) {

        page <- tryCatch({
          # Download to a local file and read that, rather than passing
          # the URL to st_read(): reading the URL directly returns the
          # right attributes but empty geometries.
          tmp_file <- tempfile(fileext = ".geojson")
          utils::download.file(url, tmp_file, quiet = TRUE, mode = "wb")
          result <- sf::st_read(tmp_file, quiet = TRUE)
          unlink(tmp_file)
          result
        }, error = function(e) {
          cat(
            "  Offset", offset, "failed (attempt", attempt, "of",
            max_retries, "):", conditionMessage(e), "\n"
          )
          NULL
        })

        if (is.null(page)) {
          Sys.sleep(3 * attempt)  # wait grows with each attempt
          attempt <- attempt + 1
        }
      }

      if (is.null(page)) {
        stop(
          "Giving up on offset ", offset, " after ", max_retries,
          " attempts. Pages already fetched are cached in '", cache_dir,
          "' — re-run with the same cache_dir to resume from here ",
          "instead of starting over."
        )
      }

      if (!is.null(page_file)) {
        saveRDS(page, page_file)
      }

      cat("  Offset", offset, "— fetched", nrow(page), "records\n")

      Sys.sleep(request_delay)
    }

    if (nrow(page) == 0) break

    pages[[length(pages) + 1]] <- page
    offset <- offset + page_size

  }

  if (length(pages) == 0) {
    return(pages)
  }

  do.call(rbind, pages)
}

