# Resistance values by land-cover class, taken from Table 4.2 of the
# author's PhD thesis. Scale 1-10; higher values are harder for a
# typical urban woodland butterfly to cross. The values are fixed and
# applied identically to every region, so regions are comparable.
# They are defined here rather than in 02_Resistance_Surface.Rmd so
# that any script can use them without building the national surface.
#
# Class IDs follow the LCM + NFI classification used throughout.
# Broadleaved (1) and coniferous (2) woodland share resistance 1, so
# they are merged into one "Woodland" class (1). Class 16 is labelled
# "Sublittoral sediment" in the thesis table and "Supra-littoral
# sediment" in the LCM documentation; the class ID and value (5) are
# the same.
resistance_lookup <- c(
  `1`  = 1,   # Woodland (broadleaved and coniferous, both 1, merged)
  `3`  = 7,   # Arable land
  `4`  = 5,   # Improved grassland
  `5`  = 2,   # Neutral grassland
  `6`  = 2,   # Calcareous grassland
  `7`  = 2,   # Acid grassland
  `8`  = 5,   # Fen, marsh and swamp
  `9`  = 4,   # Heather
  `10` = 3,   # Heather grassland
  `11` = 5,   # Bog
  `12` = 6,   # Inland rock
  `13` = 10,  # Saltwater
  `14` = 10,  # Freshwater
  `15` = 5,   # Supra-littoral rock (Maritime cliffs)
  `16` = 5,   # Sublittoral/Supra-littoral sediment (Marine sediments)
  `17` = 4,   # Littoral rock (cobbles, boulders)
  `18` = 4,   # Littoral sediment (sand, mud)
  `19` = 4,   # Saltmarsh
  # LCM class 20 is the dense "Urban" class (city centres, industrial and
  # commercial land); class 21 is "Suburban" (residential, with gardens).
  `20` = 10,  # Urban (dense urban / industrial)
  `21` = 8    # Suburban (residential)
)

